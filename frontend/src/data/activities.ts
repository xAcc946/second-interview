/** 合并补充通知后的活动列表（与后端 get_merged_activities 逻辑一致） */
export function getMergedActivities(): ActivityLike[] {
  const notices: Record<number, any[]> = {}
  const mainItems: any[] = []
  for (const item of RAW) {
    if (item.status === 'notice') {
      ;(notices[item.supplement_to] ||= []).push(item)
    } else {
      mainItems.push({ ...item })
    }
  }
  for (const item of mainItems) {
    const related = notices[item.id] || []
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    const timeline: any[] = [{ time: '原始通知', text: item.summary, is_update: false }]
    const supplements: any[] = []
    for (const n of related) {
      timeline.push({ time: `补充通知（#${String(n.id).padStart(2, '0')}）`, text: n.summary, is_update: true, changes: n.changes })
      supplements.push({ id: n.id, title: n.title, changes: n.changes })
    }
    item.timeline = timeline
    item.supplements = supplements
    item.related = related.map((n: any) => ({ id: n.id, note: '已有补充通知，信息已合并显示' }))
  }
  return mainItems as ActivityLike[]
}
